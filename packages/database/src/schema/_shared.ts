/**
 * Primary key.
 *
 * UUIDv4 generated by the database. Random ids avoid leaking row counts and
 * creation order through the API, and let a client generate an id before an
 * insert when it needs to. The index-locality cost of random UUIDs is real but
 * acceptable at this scale; moving to UUIDv7 later is a default change, not a
 * type change.
 */
export const primaryId = () => uuid('id').primaryKey().defaultRandom();

/** Foreign-key column. Named explicitly at the call site, e.g. `fk('user_id')`. */
export const fk = (name: string) => uuid(name);

/** `timestamptz` everywhere. A naive timestamp is a bug waiting for a DST boundary. */
export const createdAt = () =>
  timestamp('created_at', { withTimezone: true, mode: 'date' }).notNull().defaultNow();

/**
 * Updated-at maintained by the database.
 *
 * `$onUpdate` keeps it correct for Drizzle writes, and the column default
 * covers rows touched by migrations or manual SQL.
 */
export const updatedAt = () =>
  timestamp('updated_at', { withTimezone: true, mode: 'date' })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date());

/** Standard created/updated pair. */
export const timestamps = () => ({
  createdAt: createdAt(),
  updatedAt: updatedAt(),
});

/**
 * Soft-delete marker.
 *
 * Used where moderation or audit history must survive removal. A nullable
 * timestamp rather than a boolean, so *when* it happened is recorded too.
 */
export const deletedAt = () => timestamp('deleted_at', { withTimezone: true, mode: 'date' });

/** Case-insensitive uniqueness helper for citext-like columns. */
export const lower = (column: unknown) => sql`lower(${column})`;
