/**
 * Shared column builders and enum declarations.
 *
 * Enums are declared from the `@playanime/contracts` constants rather than
 * re-listed here. A Postgres enum and a TypeScript union that drift apart
 * produce runtime insert failures that type checking cannot catch, so there is
 * exactly one list and the database derives from it.
 */

/** Drizzle's pgEnum needs a non-empty tuple; contracts export plain arrays. */
const asTuple = <T extends string>(values: readonly T[]): [T, ...T[]] => {
  const [first, ...rest] = values;
  if (first === undefined) throw new Error('Enum must declare at least one value.');
  return [first, ...rest];
};

